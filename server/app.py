def vote_last_response(state, vote_type, model_selector):
    with open(get_conv_log_filename(), "a") as fout:
        data = {
            "tstamp": round(time.time(), 4),
            "type": vote_type,
            "model": model_selector,
            "state": state[0],
        }
        fout.write(json.dumps(data) + "\n")


def add_text(state, text, video, video_decoder, max_output_tokens):
    print(video)
    if len(text) <= 0 and video is None:
        return (state, state[1], "", None)

    if len(text) > 0 and video is not None:
        with open(video, 'rb') as f:
                data = f.read()
        img_b64_str = base64.b64encode(data).decode()
        chatbot_text = f'{text} <br><img src="data:image/png;base64,{img_b64_str}" controls width="240" height="480"></img>'
        state[1] = state[1] + [(chatbot_text, None)]
        state[0] = state[0] + [([f"Human:", video, "\nHuman:"+text], [None])]
    
    if len(text) > 0 and video is None:
        state[1] = state[1] + [(text, None)]
        state[0] = state[0] + [(["Human:" +text], [None])]

    if len(text) <= 0 and video is not None:
        with open(video, 'rb') as f:
                data = f.read()
        img_b64_str = base64.b64encode(data).decode()
        chatbot_text = f'<br><img src="data:image/png;base64,{img_b64_str}" controls width="240" height="480"></img>'
        state[1] = state[1] + [(chatbot_text, None)]
        state[0] = state[0] + [(["Human:describe this video in detail.\nHuman:", video], [None])]

    yield (state, state[1], "", None)

    responses = run(video_decoder=video_decoder, history=state[0], max_len=max_output_tokens)
    # response, out_video = 'here is the video', '/apdcephfs/share_733425/vinnylywang/zhanyuwang/Code/gvll_A100/results_videos/2bcc5af0-a2d6-4eff-8019-3546f7d2a575.mp4'

    for chunk in responses:
        text = chunk[0]
        if text[0] == ":":
            text = text[1:]
        out_video = chunk[1]
        text2 = chunk[2]

        if out_video is not None:
            if text2 is not None:
                with open(out_video, 'rb') as f:
                        data = f.read()
                img_b64_str = base64.b64encode(data).decode()
                chatbot_text = f'{text} <br><img src="data:image/png;base64,{img_b64_str}" controls width="240" height="480"></img> <br>{text2}'
                model_text = ["\nAI:"+text+"\nAI:", out_video, "\nAI:"+text2]
                state[1][-1] = list(state[1][-1])
                state[1][-1][1] = chatbot_text
                state[1][-1] = tuple(state[1][-1])

                state[0][-1] = list(state[0][-1])
                state[0][-1][1] = model_text
                state[0][-1] = tuple(state[0][-1])
                yield (state, state[1], "", None)
                return
            else:
                with open(out_video, 'rb') as f:
                        data = f.read()
                img_b64_str = base64.b64encode(data).decode()
                chatbot_text = f'{text} <br><img src="data:image/png;base64,{img_b64_str}" controls width="240" height="480"></img>'
                model_text = ["\nAI:"+text+"\nAI:", out_video]
                state[1][-1] = list(state[1][-1])
                state[1][-1][1] = chatbot_text
                state[1][-1] = tuple(state[1][-1])

